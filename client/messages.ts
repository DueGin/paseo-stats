export type MessageParams = Record<string, string | number>;

export interface MessageTree {
  [key: string]: string | MessageTree;
}

// Turns {"a.b": "x"} into {a: {b: "x"}}. Throws when a key is both a message
// and a group, which the host would reject.
export function nest(
  flat: Readonly<Record<string, string | undefined>>,
): MessageTree {
  const root: MessageTree = {};
  for (const [key, value] of Object.entries(flat)) {
    if (value === undefined) continue;
    const parts = key.split(".");
    let node = root;
    for (const part of parts.slice(0, -1)) {
      const next = node[part] ?? {};
      if (typeof next === "string")
        throw new Error(`Message key ${key} nests under a message`);
      node[part] = next;
      node = next;
    }
    const leaf = parts[parts.length - 1];
    if (leaf in node) throw new Error(`Message key ${key} is also a group`);
    node[leaf] = value;
  }
  return root;
}

export function placeholders(template: string): string[] {
  return [
    ...new Set([...template.matchAll(/\{\{(\w+)\}\}/g)].map((m) => m[1])),
  ].sort();
}
